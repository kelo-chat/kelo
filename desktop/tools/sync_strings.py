#!/usr/bin/env python3
"""Make the desktop app's text from the Android app's strings, so both always say the same thing in the same 20 languages.

    python3 desktop/tools/sync_strings.py          (or: cd desktop && ./gradlew syncStrings)

Reads   android/kelo/app/src/main/res/values*/strings*.xml   (the phone app's text; never changed here)
        desktop/strings/values*/strings*.xml                 (the few lines only the desktop app has: tray, start at login, drag & drop)
Writes  desktop/src/main/resources/i18n/<code>.json           one file per language: {"s": strings, "p": plurals, "a": arrays}
        desktop/src/generated/kotlin/chat/kelo/app/R.kt       R.string.x / R.plurals.x / R.array.x as numbers, like Android's R,
                                                             so the shared code and the desktop screens name text the same way

The text is read with android/tools/strings_res.py (aapt's escapes and quoting undone), so "don\\'t" arrives as "don't".
Run it after changing any strings.xml; `./gradlew test` checks the files are in step (StringsInStepTest).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DESKTOP = HERE.parent
ROOT = DESKTOP.parent
sys.path.insert(0, str(ROOT / "android" / "tools"))

import strings_res  # noqa: E402  (android/tools/strings_res.py)

ANDROID_RES = ROOT / "android" / "kelo" / "app" / "src" / "main" / "res"
DESKTOP_RES = DESKTOP / "strings"
OUT_JSON = DESKTOP / "src" / "main" / "resources" / "i18n"
OUT_KT = DESKTOP / "src" / "generated" / "kotlin" / "chat" / "kelo" / "app" / "R.kt"

KOTLIN_KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null", "object",
    "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
}


def write(path: Path, text: str) -> None:
    """UTF-8 with \\n line ends on every system (so a run on Windows changes nothing in git)."""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def read_dir(res: Path, values_dir: str) -> list[strings_res.Entry]:
    out: list[strings_res.Entry] = []
    d = res / values_dir
    if d.is_dir():
        for f in sorted(d.glob("strings*.xml")):
            out += strings_res.read(f)
    return out


def main() -> int:
    # the default (English) entries decide which names exist and their order
    android_default = read_dir(ANDROID_RES, "values")
    desktop_default = read_dir(DESKTOP_RES, "values")
    clash = {e.name for e in android_default} & {e.name for e in desktop_default}
    if clash:
        print(f"desktop/strings repeats names the Android app has: {sorted(clash)}", file=sys.stderr)
        return 1
    default = android_default + desktop_default
    kinds: dict[str, list[str]] = {"string": [], "plurals": [], "array": []}
    seen: set[tuple[str, str]] = set()
    for e in default:
        if (e.kind, e.name) not in seen:
            seen.add((e.kind, e.name))
            kinds[e.kind].append(e.name)

    OUT_JSON.mkdir(parents=True, exist_ok=True)
    for code, values_dir in strings_res.LOCALE_DIRS.items():
        entries = read_dir(ANDROID_RES, values_dir) + read_dir(DESKTOP_RES, values_dir)
        if code != "en":   # untranslatable lines live only in values/: every language falls back to English for them
            pass
        s: dict[str, str] = {}
        p: dict[str, dict[str, str]] = {}
        a: dict[str, list[str]] = {}
        for e in entries:
            if e.kind == "string":
                s[e.name] = e.text
            elif e.kind == "plurals":
                p[e.name] = e.quantities
            else:
                a[e.name] = e.items
        data = {"s": dict(sorted(s.items())), "p": dict(sorted(p.items())), "a": dict(sorted(a.items()))}
        write(OUT_JSON / f"{code}.json", json.dumps(data, ensure_ascii=False, indent=0, sort_keys=False) + "\n")

    def ident(name: str) -> str:
        return f"`{name}`" if name in KOTLIN_KEYWORDS else name

    lines = [
        "// Generated by desktop/tools/sync_strings.py from the Android app's strings (and desktop/strings). Do not edit by hand.",
        "@file:Suppress(\"ObjectPropertyName\", \"unused\", \"ClassName\")",
        "",
        "package chat.kelo.app",
        "",
        "/** The text's names as numbers, like Android's R: R.string.x is an index into [RNames.string]. */",
        "object R {",
    ]
    for kind in ("string", "plurals", "array"):
        lines.append(f"    object {kind} {{")
        for i, name in enumerate(kinds[kind]):
            lines.append(f"        const val {ident(name)}: Int = {i}")
        lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("/** The name behind each number of [R] (the key in src/main/resources/i18n/<code>.json). */")
    lines.append("object RNames {")
    for kind in ("string", "plurals", "array"):
        lines.append(f"    val {kind}: Array<String> = arrayOf(")
        for name in kinds[kind]:
            lines.append(f"        \"{name}\",")
        lines.append("    )")
    lines.append("}")
    OUT_KT.parent.mkdir(parents=True, exist_ok=True)
    write(OUT_KT, "\n".join(lines) + "\n")
    print(f"{len(kinds['string'])} strings, {len(kinds['plurals'])} plurals, {len(kinds['array'])} arrays in "
          f"{len(strings_res.LOCALE_DIRS)} languages -> {OUT_JSON.relative_to(ROOT)}, {OUT_KT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
