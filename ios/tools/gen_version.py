#!/usr/bin/env python3
"""version.json (repository root) -> ios/KeloCore/Sources/KeloCore/Core/KeloVersion.swift, read at build time (docs/versioning.md).

The app shows `version` to people (My, the update screens), sends it in `X-Kelo-App: ios/<version>+<CFBundleVersion>` and compiles in
`min_server` (the oldest server release it works with). CFBundleShortVersionString (MARKETING_VERSION in ios/Kelo/project.yml) and
CFBundleVersion (CURRENT_PROJECT_VERSION, raised by tools/build/ios.sh testflight) stay the App Store's own numbers.

Usage (from anywhere):
  python3 ios/tools/gen_version.py            # write
  python3 ios/tools/gen_version.py --check    # exit 1 when the written file is out of date
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "version.json"
OUT = ROOT / "ios/KeloCore/Sources/KeloCore/Core/KeloVersion.swift"
SEMVER = re.compile(r"^\d+\.\d+\.\d+$")


def render(v: dict) -> str:
    version, min_server = str(v["version"]), str(v["min_server"])
    for name, value in (("version", version), ("min_server", min_server)):
        if not SEMVER.match(value):
            raise SystemExit(f"version.json: {name} {value!r} is not MAJOR.MINOR.PATCH")
    return f'''// Generated by ios/tools/gen_version.py from version.json. Do not edit; run the script after a release bump.

/// Kelo's release version for this build (docs/versioning.md).
public enum KeloVersion {{
    /// The release people see ("0.9.0"), also in `X-Kelo-App`.
    public static let version = "{version}"
    /// The oldest Kelo server release this app works with.
    public static let minServer = "{min_server}"
}}
'''


def main() -> None:
    text = render(json.loads(SRC.read_text()))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 ios/tools/gen_version.py", file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
