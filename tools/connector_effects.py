#!/usr/bin/env python3
"""Writes docs/connector-permissions.md: for every connector, the kinds of action it has (read, change, send, delete) and the actions in
each kind, taken from the code (server/src/assistant/effects.py, presets.py, mcp_oauth.py, oauth_connect.py). A test keeps the file in step.

  uv run python tools/connector_effects.py            # print it
  uv run python tools/connector_effects.py --write    # update docs/connector-permissions.md
  uv run python tools/connector_effects.py --counts   # connectors / actions classified, how many fell to the name-verb fallback
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server" / "src"))

from assistant import effects, forbidden  # noqa: E402
from assistant.catalog import BY_ID  # noqa: E402
from assistant.effects import FAMILIES, KINDS, all_actions  # noqa: E402
from assistant.mcp_oauth import SERVICES  # noqa: E402
from assistant.oauth_connect import PROVIDERS as DEVICE  # noqa: E402
from assistant.presets import KEYS, SELF_HOSTED_IDS  # noqa: E402

DOC = ROOT / "docs" / "connector-permissions.md"
FAMILY_TITLES = {
    "mail": "Mail (Gmail, Outlook, IMAP mailboxes, Nest mail packages)", "calendar": "Google Calendar",
    "calendar_read": "Calendars that Kelo only reads (Outlook, CalDAV, Nest calendar packages)", "phone": "The shared phone",
    "key": "Services connected with a key or sign-in, and apps on your own network", "mcp": "MCP services",
    "package": "Nest packages that keep entries on this server",
}
EXAMPLES = ("send_message", "postComment", "reply_to_thread", "share_file", "invite_user", "publish_page", "delete_issue", "remove_member",
            "trash_file", "destroy_session", "purge_cache", "get_page", "list_issues", "search_docs", "read_file", "find_user",
            "query_database", "fetch_url", "create_page", "update_task", "set_status")


def connectors() -> list[tuple[str, str, str, bool]]:
    """(id, name, family, posts to people) for every connector with settings, in a stable order."""
    rows: dict[str, tuple[str, str, bool]] = {}
    name = lambda cid, fallback: BY_ID[cid].name if cid in BY_ID else fallback  # noqa: E731
    for cid in ("gmail", "imap_email", "outlook_mail"):
        rows[cid] = (name(cid, cid), "mail", False)
    rows["google_calendar"] = (name("google_calendar", "Google Calendar"), "calendar", False)
    for cid in ("outlook_calendar", "caldav_calendar"):
        rows[cid] = (name(cid, cid), "calendar_read", False)
    rows["phone"] = ("Phone", "phone", False)
    for s in SERVICES.values():
        rows.setdefault(s.id, (s.name, "mcp", False))
    for p in (k for k in KEYS.values() if not k.route):   # the VPN / Proxy connectors set a route; they have nothing to allow or ask
        rows.setdefault(p.id, (p.name, "key", p.sends))
    for d in DEVICE.values():
        for cid in d.serves:
            rows.setdefault(cid, (name(cid, d.name), "key", False))
    return sorted(((cid, nm, fam, sends) for cid, (nm, fam, sends) in rows.items()), key=lambda r: (r[2], r[1].casefold(), r[0]))


def kinds_of(family: str, sends: bool = False) -> list[str]:
    have = {a.kind for a in all_actions(family, sends=sends)}
    if family == "mcp":
        have = set(KINDS)
    return [k for k in KINDS if k in have]


def counts() -> dict[str, int]:
    rows = connectors()
    return {"connectors": len(rows),
            "actions": sum(len(all_actions(fam, sends=sends)) for _, _, fam, sends in rows),
            "families": len(FAMILIES), "static_actions": sum(len(a) for a in FAMILIES.values()),
            "name_verb_fallback_static": 0, "mcp_connectors_by_annotation_or_name": sum(1 for r in rows if r[2] == "mcp")}


def render() -> str:
    out = ["# What Kelo may do with each connector", "",
           "Generated by `tools/connector_effects.py` from the code (do not edit by hand; a test keeps it in step).", "",
           "In the app, under Connectors → a connector → *What Kelo may do*, the owner sets each **kind** of action (and, below it, each single "
           "action) to **allow**, **ask** or **off**. Nothing set means what happens today: reads run, and a change, send or delete asks where "
           "its tool asks today. `allow` means no approval card, except for payments, purchases, card and PIN steps, sign-ups and account steps, "
           "and anything the privacy guard flags: they keep their own checks always. `ask` means a card every time, even where a standing rule "
           "or a task's permission would have allowed it. `off` means the step is not run and the model is told the owner turned it off.", "",
           "API: `GET/PUT/DELETE /api/connectors/{id}/permissions` (see `server/src/assistant/permissions.py`). Kinds: " + ", ".join(KINDS) + ".", ""]
    for fam, title in FAMILY_TITLES.items():
        out += [f"## {title}", "", "| Action id | Label | Kind | Tool |", "|---|---|---|---|"]
        acts = FAMILIES[fam]
        for a in acts:
            out.append(f"| `{a.id}` | {a.label} | {a.kind} | `{effects.ACTION_TOOL.get(a.id, a.id)}` |")
        if fam == "key":
            out.append(f"| `connector_send` | {effects.KEY_SEND_ACTION.label} | send | `connector_send` |")
            out.append("")
            out.append("A service that posts to people (a messenger: `sends` in `presets.py`) has its change action as *send* instead of *change*.")
        if fam == "mcp":
            out.append("| *each tool the server lists* | the tool's name | read, change, send or delete | `mcp_call_tool` |")
            out.append("")
            out.append("The kind of an MCP tool: the server's own annotations when it gave them (`readOnlyHint` → read, `destructiveHint` → delete), "
                       "else the first verb in the tool's name: send, post, reply, share, invite, publish, message → send; delete, remove, trash, "
                       "destroy, purge → delete; get, list, search, read, find, query, fetch → read; anything else → change.")
            out.append("")
            out.append("| Tool name | Kind by name |")
            out.append("|---|---|")
            out += [f"| `{n}` | {effects.mcp_kind(n)} |" for n in EXAMPLES]
        if fam == "package":
            out.append("")
            out.append("The package's id is the connector id. A Nest connector package that keeps a mailbox or a calendar is a mail or a "
                       "read-only calendar connector; one connected with a key or a sign-in follows its kind.")
        out.append("")
    out += ["## Connectors", "", "| Connector | Id | Family | Kinds |", "|---|---|---|---|"]
    for cid, nm, fam, sends in connectors():
        out.append(f"| {nm} | `{cid}` | {fam} | {', '.join(kinds_of(fam, sends))} |")
    c = counts()
    out += ["", "## Never called or always asked", "",
            "Whatever the connector's setting, a standing rule or a task's permission says (`server/src/assistant/forbidden.py`). **never**: the call is "
            "refused before any request, whoever asks (it would break or hijack Kelo, run arbitrary code on the owner's machine, or mint a new "
            "key, token or password that would come back to Kelo). **ask**: the step always shows an Allow/Deny card, and `allow` does not skip it. "
            "Class: code, takeover (who can get in), system, data (cannot come back). Methods `*` = every method; paths are matched against the "
            "lower-cased, decoded path; a body pattern also has to match the JSON body. The model is not told this list.", "",
            "| Connector id | Mode | Methods | Path pattern | Body pattern | Class | Documentation |", "|---|---|---|---|---|---|---|"]
    for pid, r in forbidden.table():
        meth = "*" if "*" in r.methods else ", ".join(m for m in ("GET", "POST", "PUT", "PATCH", "DELETE") if m in r.methods)
        cell = lambda p: f"`{p.pattern}`".replace("|", "\\|")
        out.append(f"| `{pid}` | {r.mode} | {meth} | {cell(r.path)} | {cell(r.body) if r.body else ''} | {r.why} | "
                   f"{r.doc}{'' if r.sure else ' (conservative prefix)'} |")
    out += ["", f"{c['connectors']} connectors with settings, {c['actions']} actions in them ({c['static_actions']} distinct actions in "
            f"{c['families']} families). Every tool of every family is classified by hand above; only the tools an MCP server lists are "
            f"classified at run time (annotations first, then the verbs in the name). Installed Nest packages are added when installed.", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if "--counts" in argv:
        for k, v in counts().items():
            print(f"{k}: {v}")
        return 0
    text = render()
    if "--write" in argv:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
