#!/usr/bin/env python3
"""Android string resources -> the iPhone app's strings, so both apps show the same words in the same 20 languages.

Reads apps/shared/strings/values*/strings*.xml (the text of all apps, Android format; strings_desktop*.xml, the desktop-only lines, are skipped) (with apps/android/tools/strings_res.py, the same reader the Android checks
use, so aapt's escapes and quoting are undone the same way) and writes, for each language of core/Languages.kt:

  apps/ios/KeloUI/Sources/KeloShared/Resources/<lang>.lproj/Localizable.strings

plus apps/ios/KeloUI/Sources/KeloShared/Strings/R.swift, the keys as Swift constants named exactly like Android's R.string / R.plurals /
R.array, so Kotlin `stringResource(R.string.connect_title)` becomes Swift `L(R.string.connect_title)` and a typo fails to compile.

How the entries are stored (read by KeloShared/Strings/Strings.swift):
  - a string:        "name" = "text";
  - a plural:        "name##one" = "..."; "name##other" = "...";   (CLDR categories; the Swift side picks one by PluralRules)
  - a string array:  "name##0" = "..."; "name##1" = "...";  and "name##count" = "2";
Placeholders stay in Android's syntax (%1$s, %2$d, %s, %d, %%); Strings.format fills them, so nothing is converted and a
translation never breaks on a placeholder change.

iPhone-only words (Face ID, iOS settings, EventKit) that Android has no string for live in apps/ios/tools/ios_strings*.json (one file per app
area) as {"name": {"en": "...", "ko": "...", ...}}; they are added to every language that has them (English is required) and to R.string.

Strings marked translatable="false" are written only to en.lproj (the fallback for every language, as values/ is on Android).

Usage (from the repository root):
  python3 apps/ios/tools/gen_strings.py            # write
  python3 apps/ios/tools/gen_strings.py --check    # exit 1 when the written files are out of date (CI / before a commit)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "apps" / "android" / "tools"))
import strings_res as sr  # noqa: E402  (apps/android/tools/strings_res.py)

RES = ROOT / "apps" / "shared" / "strings"
OUT = ROOT / "apps" / "ios" / "KeloUI" / "Sources" / "KeloShared"
SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init", "inout", "internal", "let",
    "open", "operator", "private", "protocol", "public", "rethrows", "static", "struct", "subscript", "typealias", "var", "break",
    "case", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return", "switch",
    "where", "while", "as", "catch", "false", "is", "nil", "super", "self", "Self", "throw", "throws", "true", "try", "Type",
}


def quote(s: str) -> str:
    """A .strings literal (UTF-8 file; backslash, quote and control characters escaped)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r") + '"'


def read_dir(values_dir: str) -> list[sr.Entry]:
    entries: list[sr.Entry] = []
    for f in sr.string_files(RES, values_dir):
        if f.name.startswith("strings_desktop"):   # the desktop app's own lines: the iPhone has none of them
            continue
        entries += sr.read(f)
    return entries


def pairs(entries: list[sr.Entry], include_untranslatable: bool) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for e in entries:
        if not e.translatable and not include_untranslatable:
            continue
        if e.kind == "string":
            out.append((e.name, e.text))
        elif e.kind == "plurals":
            out += [(f"{e.name}##{q}", t) for q, t in e.quantities.items()]
        else:
            out += [(f"{e.name}##{i}", t) for i, t in enumerate(e.items)]
            out.append((f"{e.name}##count", str(len(e.items))))
    return out


def render_strings(lang: str, items: list[tuple[str, str]]) -> str:
    head = (f"/* Generated by apps/ios/tools/gen_strings.py from apps/android/kelo/app/src/main/res/{sr.LOCALE_DIRS[lang]}/strings*.xml"
            " - do not edit; change the Android strings and generate again. */\n")
    return head + "".join(f"{quote(k)} = {quote(v)};\n" for k, v in items)


def ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def render_swift(entries: list[sr.Entry]) -> str:
    kinds = {"string": [], "plurals": [], "array": []}
    for e in entries:
        kinds[e.kind].append(e.name)
    lines = [
        "// Generated by apps/ios/tools/gen_strings.py from the Android app's values/strings*.xml. Do not edit.",
        "// The names are Android's (R.string.x, R.plurals.x, R.array.x), so a Kotlin screen ports word for word:",
        "//   stringResource(R.string.connect_title)             ->  L(R.string.connect_title)",
        "//   stringResource(R.string.connect_step1, path)       ->  L(R.string.connect_step1, path)",
        "//   pluralStringResource(R.plurals.count_new, n, n)    ->  P(R.plurals.count_new, n, n)",
        "//   stringArrayResource(R.array.privacy_titles)        ->  LA(R.array.privacy_titles)",
        "// swiftlint:disable all",
        "",
        "public enum R {",
    ]
    for kind, type_name, swift_type in (("string", "string", "StringKey"), ("plurals", "plurals", "PluralKey"),
                                        ("array", "array", "ArrayKey")):
        lines.append(f"    public enum {type_name} {{")
        for n in sorted(set(kinds[kind])):
            lines.append(f'        public static let {ident(n)} = {swift_type}("{n}")')
        lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


IOS_ONLY_DIR = ROOT / "apps" / "ios" / "tools"
UNUSED_FILE = IOS_ONLY_DIR / "ios_unused_strings.txt"


def unused_names() -> set[str]:
    """The Android names the iPhone app never reads (ios_unused_strings.txt, written by --find-unused): left out of the iPhone's
    R.swift and Localizable.strings only. The shared strings stay as they are: Android and the desktop app read them."""
    if not UNUSED_FILE.exists():
        return set()
    return {l.strip() for l in UNUSED_FILE.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")}


def find_unused() -> list[str]:
    """Every name in the shared strings (and ios_strings*.json) that no Swift file of the app, its tests or its UI tests mentions as
    a word, and that is not the start of a name built at run time (a literal like "vault_mode_\\(m.rawValue)" keeps all names that
    begin with "vault_mode_"). The generated R.swift does not count."""
    import re
    token = re.compile(r"[A-Za-z][A-Za-z0-9_]*")
    prefix = re.compile(r'"([a-z][a-z0-9_]*_)\\\(')
    dotted = re.compile(r'"([a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+)"')
    dotted_prefix = re.compile(r'"([a-z][a-z0-9_]*(?:\.[a-z0-9_]+)*\.)\\\(')
    used: set[str] = set()
    prefixes: set[str] = set()
    for base in (ROOT / "apps" / "ios" / "KeloUI", ROOT / "apps" / "ios" / "KeloCore", ROOT / "apps" / "ios" / "Kelo"):
        for f in base.rglob("*.swift"):
            if f.name == "R.swift" or ".build" in f.parts:
                continue
            text = f.read_text(encoding="utf-8")
            used.update(token.findall(text))
            prefixes.update(prefix.findall(text))
            # a dotted literal ("connector.group.dev") is turned into a name at run time (dots to underscores)
            used.update(d.replace(".", "_") for d in dotted.findall(text))
            prefixes.update(d.replace(".", "_") for d in dotted_prefix.findall(text))
    names = {e.name for e in read_dir("values")} | set(ios_only())
    return sorted(n for n in names if n not in used and not any(n.startswith(p) for p in prefixes))


def ios_only() -> dict[str, dict[str, str]]:
    """Every apps/ios/tools/ios_strings*.json (one per app area, e.g. ios_strings_chat.json), merged; a name may appear only once."""
    import json
    data: dict[str, dict[str, str]] = {}
    for f in sorted(IOS_ONLY_DIR.glob("ios_strings*.json")):
        for name, by_lang in json.loads(f.read_text(encoding="utf-8")).items():
            if name in data:
                raise SystemExit(f"{f.name}: {name} is already defined in another ios_strings*.json")
            if "en" not in by_lang:
                raise SystemExit(f"{f.name}: {name} has no English")
            data[name] = by_lang
    return data


def build() -> dict[Path, str]:
    files: dict[Path, str] = {}
    skip = unused_names()
    default = [e for e in read_dir("values") if e.name not in skip]
    names = {e.name for e in default}
    extra = {n: t for n, t in ios_only().items() if n not in skip}
    clash = names & extra.keys()
    if clash:
        raise SystemExit(f"ios_strings.json repeats Android names: {sorted(clash)}")
    for lang, values_dir in sr.LOCALE_DIRS.items():
        entries = default if lang == "en" else [e for e in read_dir(values_dir) if e.name in names]
        entries = entries + [sr.Entry("string", n, True, text=t[lang]) for n, t in extra.items() if lang in t]
        files[OUT / "Resources" / f"{lang}.lproj" / "Localizable.strings"] = render_strings(lang, pairs(entries, lang == "en"))
    files[OUT / "Strings" / "R.swift"] = render_swift(default + [sr.Entry("string", n, True, text=t["en"]) for n, t in extra.items()])
    return files


# The app's Info.plist permission texts, per language: from Android strings where Android asks for the same thing (joined with a
# space), else from apps/ios/tools/infoplist_strings.json (English required; a language without its own text falls back to English).
INFOPLIST_FROM_ANDROID: dict[str, list[str]] = {
    # NSCameraUsageDescription: iPhone-only (infoplist_strings.json): the camera also scans cards and takes chat photos here
    "NSCalendarsFullAccessUsageDescription": ["device_calendar_does", "device_calendar_sends"],
    "NSCalendarsUsageDescription": ["device_calendar_does", "device_calendar_sends"],
    "NSContactsUsageDescription": ["device_contacts_does", "device_contacts_sends"],
    # NSLocationWhenInUseUsageDescription: iPhone-only (infoplist_strings.json): the briefing's weather and "near me" questions
}
# keys whose Android texts are a title and a sentence: joined with a dash instead of a space
INFOPLIST_JOIN: dict[str, str] = {}
INFOPLIST_OUT = ROOT / "apps" / "ios" / "Kelo" / "App" / "Resources"
SHARE_OUT = ROOT / "apps" / "ios" / "Kelo" / "Share" / "Resources"
LIVE_NAMES = ["live_working", "live_waiting", "live_done", "live_failed", "live_stopped", "live_stop", "live_steps"]
LIVE_OUT = ROOT / "apps" / "ios" / "Kelo" / "Live" / "Resources"   # the Live Activity extension: exactly the live_* names


def build_infoplist() -> dict[Path, str]:
    import json
    extra = json.loads((IOS_ONLY_DIR / "infoplist_strings.json").read_text(encoding="utf-8"))
    english = {e.name: e.text for e in read_dir("values") if e.kind == "string"}
    files: dict[Path, str] = {}
    for lang, values_dir in sr.LOCALE_DIRS.items():
        texts = {e.name: e.text for e in read_dir(values_dir) if e.kind == "string"}
        items: list[tuple[str, str]] = []
        for key, names in INFOPLIST_FROM_ANDROID.items():
            items.append((key, INFOPLIST_JOIN.get(key, " ").join(texts.get(n) or english[n] for n in names)))
        for key, by_lang in extra.items():
            items.append((key, by_lang.get(lang) or by_lang["en"]))
        files[INFOPLIST_OUT / f"{lang}.lproj" / "InfoPlist.strings"] = render_strings(lang, items)
        # the banner of a push from APNs (loc-key in the push; Localizable.strings of the app bundle itself, not the package's)
        push = json.loads((IOS_ONLY_DIR / "push_strings.json").read_text(encoding="utf-8"))
        files[INFOPLIST_OUT / f"{lang}.lproj" / "Localizable.strings"] = render_strings(
            lang, [(key, by_lang.get(lang) or by_lang["en"]) for key, by_lang in push.items()])
        # the share extension's name in the share sheet: Android's own label for its share target
        files[SHARE_OUT / f"{lang}.lproj" / "InfoPlist.strings"] = render_strings(
            lang, [("CFBundleDisplayName", texts.get("share_label") or english["share_label"])])
        # the Live Activity extension's words (strings_live.xml; English where a language lacks one)
        files[LIVE_OUT / f"{lang}.lproj" / "Localizable.strings"] = render_strings(
            lang, [(n, texts.get(n) or english[n]) for n in LIVE_NAMES])
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="only check that the generated files are up to date")
    ap.add_argument("--find-unused", action="store_true", help="rewrite ios_unused_strings.txt: the names no Swift file mentions")
    args = ap.parse_args()
    if args.find_unused:
        found = find_unused()
        UNUSED_FILE.write_text("# Names the iPhone app never reads, left out of its R.swift and Localizable.strings (gen_strings.py --find-unused).\n"
                               + "".join(f"{n}\n" for n in found), encoding="utf-8")
        print(f"{len(found)} names the iPhone app never reads")
        return 0
    files = build()
    files.update(build_infoplist())
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    keys = sum(1 for line in files[OUT / "Resources" / "en.lproj" / "Localizable.strings"].splitlines() if " = " in line)
    print(f"{len(sr.LOCALE_DIRS)} languages, {keys} entries in en; {len(stale)} file(s) written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
